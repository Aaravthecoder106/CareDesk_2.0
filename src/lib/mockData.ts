// Helper to generate past dates relative to reference date for stable SSR
const daysAgo = (days: number, timeStr = '08:30:00'): string => {
  const d = new Date('2026-10-20T12:00:00Z');
  d.setUTCDate(d.getUTCDate() - days);
  return `${d.toISOString().split('T')[0]}T${timeStr}.000Z`;
};

